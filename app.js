/* =====================================================
   12. МҰҒАЛІМ БАҒАСЫН САҚТАУ
   ===================================================== */

function saveTeacherGrades(resultId, detailsElement) {
    const results = getResults();
    const result = results.find(item => item.id === resultId);

    if (!result) return;

    const selectedText = texts.find(item => item.id === result.textId);
    if (!selectedText) return;

    const inputs = detailsElement.querySelectorAll(
        "input[data-question-id]"
    );

    const grades = {};
    let manualTotal = 0;
    let invalid = false;

    inputs.forEach(input => {
        const questionId = input.dataset.questionId;
        const question = selectedText.questions.find(
            item => item.id === questionId
        );

        if (!question) return;

        const value = input.value.trim();

        if (value === "") {
            grades[questionId] = 0;
            return;
        }

        const score = Number(value);

        if (
            !Number.isInteger(score) ||
            score < 0 ||
            score > question.manual
        ) {
            invalid = true;
            return;
        }

        grades[questionId] = score;
        manualTotal += score;
    });

    if (invalid) {
        alert("Ұпайды дұрыс енгізіңіз. Әр тапсырманың шекті ұпайын сақтаңыз.");
        return;
    }

    result.manualGrades = grades;
    result.manualScore = manualTotal;

    const finalScore = (result.automaticScore || 0) + manualTotal;
    result.score = finalScore;
    result.status = "Тексерілді";

    saveResults(results);

    alert(`Баға сақталды! Қорытынды нәтиже: ${finalScore} / 20`);
    showTeacherPanel();
}

