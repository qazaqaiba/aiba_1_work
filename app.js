/* =====================================================
   7. ОҚУШЫ ЖАУАПТАРЫН ЖИНАУ
   ===================================================== */

function collectAnswer(question) {
    if (question.type === "radio") {
        return document.querySelector(
            `input[name="${question.id}"]:checked`
        )?.value || "";
    }

    if (question.type === "multi") {
        return [...document.querySelectorAll(
            `input[name="${question.id}"]:checked`
        )].map(input => input.value);
    }

    if (question.type === "matching") {
        return question.fields.map((field, index) =>
            getValue(`${question.id}_${index}`)
        );
    }

    if (question.type === "textarea") {
        return getValue(question.id).trim();
    }

    return "";
}

/* =====================================================
   8. АВТОМАТТЫ ТЕКСЕРУ
   ===================================================== */

function checkQuestion(question, answer) {
    if (!question.points) return 0;

    if (question.type === "radio") {
        return answer === question.key ? question.points : 0;
    }

    if (question.type === "multi") {
        const selected = answer || [];
        const correct = question.key || [];

        let score = 0;

        correct.forEach(item => {
            if (selected.includes(item)) score++;
        });

        selected.forEach(item => {
            if (!correct.includes(item)) score--;
        });

        return Math.max(0, Math.min(question.points, score));
    }

    if (question.type === "matching") {
        let score = 0;

        question.fields.forEach((field, index) => {
            if (answer[index] === field.key) score++;
        });

        return Math.min(question.points, score);
    }

    return 0;
}

